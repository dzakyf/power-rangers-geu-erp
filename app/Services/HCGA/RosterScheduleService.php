<?php

namespace App\Services\HCGA;

use App\Models\HCGA\EmployeeRosterAssignment;
use App\Models\HCGA\EmployeeSchedule;
use App\Models\HCGA\MasterShift;
use App\Models\HCGA\RosterPattern;
use Carbon\Carbon;
use Carbon\CarbonPeriod;
use Illuminate\Support\Facades\DB;
use InvalidArgumentException;

class RosterScheduleService
{
    /**
     * Generate atau sync jadwal harian untuk seorang karyawan dalam rentang tanggal tertentu.
     *
     * @param string $userId
     * @param string $startDate 'Y-m-d'
     * @param string $endDate   'Y-m-d'
     * @param string|null $actor
     * @return array
     */
    public function generateEmployeeSchedule(string $userId, string $startDate, string $endDate, ?string $actor = 'SYSTEM'): array
    {
        $start = Carbon::parse($startDate)->startOfDay();
        $end = Carbon::parse($endDate)->endOfDay();

        if ($end->lt($start)) {
            throw new InvalidArgumentException("Tanggal akhir tidak boleh lebih awal dari tanggal mulai.");
        }

        // Ambil penugasan roster aktif yang beririsan dengan rentang tanggal
        $assignments = EmployeeRosterAssignment::where('user_id', $userId)
            ->where('status', 'ACTIVE')
            ->where(function ($query) use ($startDate, $endDate) {
                $query->where('start_date', '<=', $endDate)
                    ->where(function ($sub) use ($startDate) {
                        $sub->whereNull('end_date')
                            ->orWhere('end_date', '>=', $startDate);
                    });
            })
            ->orderBy('start_date', 'asc')
            ->get();

        if ($assignments->isEmpty()) {
            return [
                'success' => false,
                'message' => "Tidak ada penugasan roster aktif untuk karyawan {$userId} pada periode tersebut.",
                'generated_count' => 0,
            ];
        }

        $generatedCount = 0;
        $period = CarbonPeriod::create($start, $end);

        DB::beginTransaction();
        try {
            foreach ($period as $date) {
                $dateStr = $date->format('Y-m-d');

                // Cari assignment yang berlaku pada tanggal ini
                $currentAssign = $assignments->first(function ($item) use ($dateStr) {
                    $validStart = $item->start_date <= $dateStr;
                    $validEnd = is_null($item->end_date) || $item->end_date >= $dateStr;
                    return $validStart && $validEnd;
                });

                if (!$currentAssign) {
                    continue;
                }

                $pattern = RosterPattern::with('details')->find($currentAssign->pattern_id);
                if (!$pattern || $pattern->details->isEmpty() || $pattern->cycle_days == 0) {
                    continue;
                }

                // Kalkulasi hari dalam siklus roster
                $assignStartDate = Carbon::parse($currentAssign->start_date)->startOfDay();
                $diffDays = $assignStartDate->diffInDays($date);

                // Offset dari start_day_sequence (misal mulai dari sequence ke-2)
                $seqIndex = (($diffDays + ($currentAssign->start_day_sequence - 1)) % $pattern->cycle_days) + 1;

                $detail = $pattern->details->firstWhere('day_sequence', $seqIndex);
                if (!$detail) {
                    continue;
                }

                // Simpan atau perbarui employee_schedules (jangan menimpa MANUAL_OVERRIDE atau LEAVE)
                $existing = EmployeeSchedule::where('user_id', $userId)
                    ->where('work_date', $dateStr)
                    ->first();

                if ($existing) {
                    if ($existing->source_type === 'PATTERN') {
                        $existing->update([
                            'shift_id'   => $detail->shift_id,
                            'updated_by' => $actor,
                            'updated_at' => now(),
                        ]);
                        $generatedCount++;
                    }
                } else {
                    EmployeeSchedule::create([
                        'user_id'     => $userId,
                        'work_date'   => $dateStr,
                        'shift_id'    => $detail->shift_id,
                        'source_type' => 'PATTERN',
                        'notes'       => "Generated by Roster Pattern: {$pattern->pattern_name} (Hari ke-{$seqIndex})",
                        'created_by'  => $actor,
                        'created_at'  => now(),
                    ]);
                    $generatedCount++;
                }
            }

            DB::commit();

            return [
                'success'         => true,
                'message'         => "Jadwal berhasil di-generate sebanyak {$generatedCount} hari.",
                'generated_count' => $generatedCount,
            ];
        } catch (\Exception $e) {
            DB::rollBack();
            throw $e;
        }
    }

    /**
     * Pasang jadwal shift manual (Manual Override) untuk tanggal spesifik (misal tukar shift).
     */
    public function setManualSchedule(string $userId, string $workDate, int $shiftId, string $notes = '', ?string $actor = 'SYSTEM'): EmployeeSchedule
    {
        $shift = MasterShift::findOrFail($shiftId);

        return EmployeeSchedule::updateOrCreate(
            [
                'user_id'   => $userId,
                'work_date' => $workDate,
            ],
            [
                'shift_id'    => $shift->id,
                'source_type' => 'MANUAL_OVERRIDE',
                'notes'       => $notes ?: "Penyesuaian Manual Shift: {$shift->shift_name}",
                'updated_by'  => $actor,
                'updated_at'  => now(),
            ]
        );
    }
}

